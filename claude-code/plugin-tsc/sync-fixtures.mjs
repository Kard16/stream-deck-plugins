// Copies the protocol's fixtures into claude-code/plugin/tests/fixtures.gen.ts. `claude plugin test` loads only
// code (.ts, .js, ...) from inside the plugin's folder, so the plugin's tests can't read
// claude-code/protocol/fixtures/*.jsonl or vectors.json themselves. Each fixture line and the vectors go in
// verbatim: JSON is valid TypeScript.
//
//   mise exec -- node claude-code/plugin-tsc/sync-fixtures.mjs           rewrite fixtures.gen.ts
//   mise exec -- node claude-code/plugin-tsc/sync-fixtures.mjs --check   exit 1 when it's out of date
//
// Run it after make-fixtures.mjs changes the fixtures.

import fs from 'node:fs'
import path from 'node:path'
import { fileURLToPath } from 'node:url'

const here = path.dirname(fileURLToPath(import.meta.url))
const FIXTURES = path.join(here, '..', 'protocol', 'fixtures')
const OUT = path.join(here, '..', 'plugin', 'tests', 'fixtures.gen.ts')

function render() {
  const out = [
    '// Generated by claude-code/plugin-tsc/sync-fixtures.mjs from claude-code/protocol/fixtures/. Do not edit: run',
    '// `mise exec -- node claude-code/plugin-tsc/sync-fixtures.mjs` after the fixtures change.',
    '',
    '/** One line of a fixture conversation (PROTOCOL.md, "Fixtures"). */',
    'export type FixtureLine = Readonly<Record<string, unknown>>',
    '',
    '/** One of vectors.json\'s inputs, with its canonical JSON, fingerprint and summary. */',
    'export type Vector = { readonly tool: string; readonly input: unknown; readonly canonical: string; readonly fp: string; readonly summary: string }',
    '',
    'export const FIXTURES: Readonly<Record<string, readonly FixtureLine[]>> = {',
  ]
  const names = fs.readdirSync(FIXTURES).filter((n) => n.endsWith('.jsonl')).sort()
  for (const name of names) {
    const lines = fs.readFileSync(path.join(FIXTURES, name), 'utf8').split('\n').filter((l) => l.trim() !== '')
    for (const line of lines) JSON.parse(line)
    out.push(`  ${JSON.stringify(name.slice(0, -'.jsonl'.length))}: [`)
    for (const line of lines) out.push(`    ${line},`)
    out.push('  ],')
  }
  out.push('}', '')
  const vectors = fs.readFileSync(path.join(FIXTURES, 'vectors.json'), 'utf8').trimEnd()
  JSON.parse(vectors)
  out.push(`export const VECTORS: readonly Vector[] = ${vectors}`, '')
  return { text: out.join('\n'), fixtures: names.length }
}

const { text, fixtures } = render()
const rel = path.relative(process.cwd(), OUT)
if (process.argv.includes('--check')) {
  const current = fs.existsSync(OUT) ? fs.readFileSync(OUT, 'utf8') : ''
  if (current !== text) {
    console.error(`${rel} is out of date with claude-code/protocol/fixtures/: run this script without --check`)
    process.exit(1)
  }
  console.log(`${rel} matches the ${fixtures} fixtures and vectors.json`)
} else {
  fs.writeFileSync(OUT, text)
  console.log(`wrote ${rel}: ${fixtures} fixtures and vectors.json`)
}
